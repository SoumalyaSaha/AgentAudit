"""
Run-history persistence for the dashboard.

Every completed AgentAudit run is appended to
`dashboard/data/run_history.json` as a structured record: verdict,
per-check pass/fail, per-check durations, backend, Nemotron mode and
parsed pytest counts. The dashboard renders strictly from this file --
it never invents numbers.

The file is also the seed for the dashboard's aggregate views, so it is
regenerated by actually RUNNING the scenarios (never hand-written):
    python engine/run_demo.py all            # 5 local/fixture runs
    python engine/run_demo.py both --backend sandbox   # live sandbox runs
"""

from __future__ import annotations

import json
import os
import uuid
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_HISTORY_PATH = REPO_ROOT / "dashboard" / "data" / "run_history.json"
ENGINE_INFO_PATH = REPO_ROOT / "dashboard" / "data" / "engine_info.json"


def history_path() -> Path:
    return Path(os.environ.get("AGENTAUDIT_HISTORY_PATH", str(DEFAULT_HISTORY_PATH)))


def _load(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    return data if isinstance(data, list) else []


def append_run(record: dict, path: Path | None = None) -> Path:
    """Append one run record to the history file and return its path."""
    path = path or history_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    runs = _load(path)
    runs.append(record)
    path.write_text(json.dumps(runs, indent=2) + "\n", encoding="utf-8")
    return path


def new_run_id() -> str:
    return f"run-{uuid.uuid4().hex[:8]}"


def write_engine_info(extra: dict | None = None) -> Path:
    """Export engine constants (model names, scenario catalog) for the UI.

    Model names come straight from engine/inference_client.py so the
    dashboard can never drift from the code.
    """
    import inference_client
    import scenarios

    info = {
        "models": {
            "super": inference_client.NEMOTRON_SUPER,
            "nano": inference_client.NEMOTRON_NANO,
        },
        "inference_endpoint": inference_client.NEBIUS_BASE_URL,
        "checks": [
            {"key": "T", "name": "Test Tampering", "uses_model": False},
            {"key": "R", "name": "Baseline Regression", "uses_model": False},
            {"key": "B", "name": "Blind-Spot Coverage", "uses_model": True},
            {"key": "D", "name": "Description Match", "uses_model": True},
        ],
        "scenarios": {
            name: {
                "patch": meta["patch"],
                "description": meta["description"],
            }
            for name, meta in scenarios.SCENARIOS.items()
        },
        "demo_scenarios": scenarios.DEMO_SCENARIOS,
        # Static descriptive data lives here (not in the callers) so every
        # process that rewrites this file -- run_demo.py or audit_server.py
        # -- produces the identical shape. Whoever writes last must not
        # silently drop fields the other one added.
        "backends": {
            "local": "LocalBackend (filesystem snapshot, offline, deterministic)",
            "sandbox": "Nebius Sandboxes / ConTree (live, real API calls)",
        },
        "nemotron_modes": {
            "fixture": "Recorded Nemotron responses replayed offline (deterministic)",
            "live": "Live Nemotron inference via Nebius Token Factory",
        },
    }
    if extra:
        info.update(extra)
    ENGINE_INFO_PATH.parent.mkdir(parents=True, exist_ok=True)
    ENGINE_INFO_PATH.write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
    return ENGINE_INFO_PATH
